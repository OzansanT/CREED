import { readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const excludedDirectories = new Set([".git", "node_modules"]);

function collectFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if (entry.isDirectory() && excludedDirectories.has(entry.name)) return [];
    const fullPath = resolve(directory, entry.name);
    if (entry.isDirectory()) return collectFiles(fullPath);
    if (!entry.isFile() && !statSync(fullPath).isFile()) return [];
    return [relative(repositoryRoot, fullPath).replaceAll("\\", "/")];
  });
}

const files = collectFiles(repositoryRoot).sort((left, right) => left.localeCompare(right));
const content = [
  "// Generated by scripts/build-source-files.mjs.",
  "// This is the authoritative, sorted inventory used by the Explorer UI.",
  "export const WORKSPACE_FILES = Object.freeze([",
  ...files.map((file) => "  " + JSON.stringify(file) + ","),
  "]);",
  ""
].join("\n");

writeFileSync(resolve(repositoryRoot, "js/components/editor-panel/source-files.js"), content);
